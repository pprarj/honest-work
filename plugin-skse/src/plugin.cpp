// Lean entry point: fans out the SKSE message dispatch to whichever module needs a
// lifecycle hook. UI::PrismaPanel needs Prisma UI to already be loaded
// (kDataLoaded, D079); Core::ProfessionsRegistry needs RE::TESDataHandler
// to already be populated (same message, confirmed safe there by
// D078) - the merge runs first so the
// merged professions_merged.json/contract_types_merged.json files exist
// before anything else in this load could plausibly want them.

#include "Core/AppConfig.h"
#include "Core/Log.h"
#include "Core/ProfessionsRegistry.h"
#include "Core/TestChannel.h"
#include "Core/WorkerNatives.h"
#include "UI/PrismaPanel.h"
#include "UI/SettingsPage.h"
#include "Version.h"

namespace
{
	void OnMessage(SKSE::MessagingInterface::Message* a_msg)
	{
		if (!a_msg) {
			return;
		}

		// The watched bandits belong to one session of the game: the worker
		// script watches again on load (RestoreTravelTarget).
		if (a_msg->type == SKSE::MessagingInterface::kNewGame ||
			a_msg->type == SKSE::MessagingInterface::kPreLoadGame) {
			HonestWork::Core::WorkerNatives::ClearWatched();
		}

		if (a_msg->type == SKSE::MessagingInterface::kDataLoaded) {
			HonestWork::Core::WorkerNatives::OnDataLoaded();
			HonestWork::Core::ProfessionsRegistry::MergeAll();
			HonestWork::UI::PrismaPanel::OnDataLoaded();
			// Fase 19 (D195): optional - without the SKSE Menu Framework this
			// only logs, and the config stays in the TOML.
			HonestWork::UI::SettingsPage::Register();
		}
	}
}

// SKSEPluginLoad is the modern CommonLibSSE-NG entry point. The version
// boilerplate (SKSEPlugin_Version) is auto-generated by add_commonlibsse_plugin.
SKSEPluginLoad(const SKSE::LoadInterface* a_skse)
{
	if (!HonestWork::Core::Log::Init()) {
		SKSE::stl::report_and_fail("SKSE log directory not provided.");
	}

	// a_log = false: with the default (true), CommonLibSSE-NG builds its own
	// logger on top of the one Log::Init() just configured - it truncates the
	// file, replaces the pattern, and drops trace to info in release builds.
	// Confirmed in src/SKSE/API.cpp:97-100 and src/SKSE/Logger.cpp:126-151 of
	// v6.7.1. Do not drop the second argument. Campaign
	// 2026-09-04-skse-init-preserva-o-logger-do-plugin.
	SKSE::Init(a_skse, false);

	// Config is loaded before the first "loaded successfully" line so that
	// line already reflects the configured log level.
	HonestWork::Core::AppConfig::Load();
	HonestWork::Core::Log::ApplyConfiguredLevel(HonestWork::Core::AppConfig::Get().logLevel);

	spdlog::info("{} v{} loaded successfully.",
		HonestWork::Version::kProjectName, HonestWork::Version::kString);

	if (!SKSE::GetMessagingInterface()->RegisterListener(OnMessage)) {
		spdlog::error("Failed to register the SKSE message listener - the operator panel will not initialize.");
		return false;
	}

	// D215/D216: the worker script's linked reference and the encounter bandit's
	// death, formerly taken from the PO3 Papyrus Extender.
	if (!HonestWork::Core::WorkerNatives::Register()) {
		spdlog::error("WorkerNatives: Papyrus registration refused - WOSK_Native unbound, workers cannot be pointed at a destination.");
	}

	// Not fatal to loading (the panel still works), but without it every
	// contract is refused: the worker script reads professions and contract
	// types only through these natives (B003, D099).
	if (!HonestWork::Core::ProfessionsRegistry::RegisterNatives()) {
		spdlog::error("ProfessionsRegistry: Papyrus registration refused - WOSK_Registry natives unbound, contracts cannot read their data.");
	}

	// D104 etapa 3: without these the recruiter cannot show the candidate list.
	if (!HonestWork::UI::PrismaPanel::RegisterNatives()) {
		spdlog::error("PrismaPanel: Papyrus registration refused - WOSK_Panel natives unbound, the Recruit tab cannot open.");
	}

	// Non-fatal: without it only the test harness loses its channel, and the
	// mod itself never calls this native.
	if (!HonestWork::Core::TestChannel::Register()) {
		spdlog::error("TestChannel: Papyrus registration refused - the test harness will have no output channel.");
	}

	return true;
}
